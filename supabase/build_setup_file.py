"""Rebuilds setup_new_environment.sql from the pieces it is made of.

Run from the project root after changing any of the parts below:
    python supabase/build_setup_file.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

PARTS = [
    ('SCHEMA', 'reset_and_rebuild.sql',
     'All tables, views, functions, triggers, RLS policies, storage buckets,\n'
     '-- scheduled jobs and reference data (33 barangays, permit types,\n'
     '-- container types).'),
    ('ACCOUNTS AND STATIONS', 'seed_test_accounts.sql',
     'admin@, owner1@ (Buenavista), owner2@ (Navarro Springs), driver1@,\n'
     '-- driver2@, customer1@ -- pre-confirmed, stations accredited.'),
    ('MORE ROLE ACCOUNTS', 'seed_role_accounts.sql',
     'admin2@, driver3@, driver4@, customer2@, suspended@, owner3@ (station\n'
     '-- not yet accredited), superadmin1@, superadmin2@, staff1@.'),
    ('OFFICER ROLE ACCOUNTS', 'seed_officer_accounts.sql',
     'compliance1@, workforce1@, content1@, viewer1@ (Officer123!).'),
    ('SAMPLE PRODUCTS', 'seed_sample_products.sql',
     'What each seeded station sells and for how much, so customers can order.'),
    ('DEMO CONTENT', 'seed_demo_content.sql',
     'Bulletins with reactions and comments, station reviews, events.'),
    ('EVALUATION DATA', 'seed_evaluation_data.sql',
     'Orders in every live status (one mid-delivery), container balances,\n'
     '-- settlements awaiting confirmation, a permit pending review, and a\n'
     '-- disposable account for testing deletion.'),
    ('TEST EXTRAS', 'seed_test_extras.sql',
     'Fixed staff codes, and driver2 flagged through a confirmed incident.'),
]

HEADER = """-- =====================================================================
-- GENTRI WASA -- COMPLETE ENVIRONMENT SETUP
-- =====================================================================
-- Brings a brand-new, empty Supabase project to the same state as the
-- testing project: the whole database plus the test accounts and demo
-- data. Paste this whole file into the SQL Editor and run it once.
--
-- Generated by supabase/build_setup_file.py -- edit the parts, not this.
-- It is, in order:
{parts}
--
-- WARNING: step 1 drops every application table before recreating it.
-- Run this ONLY against a project you intend to build from scratch. It is
-- not an upgrade path for a project that already holds real data.
--
-- If it times out partway, run it again from the top: every DROP is
-- guarded and every seed skips accounts that already exist.
--
-- The dashboard steps that SQL cannot do are in docs/HANDOVER_DATABASE.md.
-- A check runs at the very end; compare its numbers with the expected ones.
-- =====================================================================
"""

FOOTER = """


-- =====================================================================
-- FINAL CHECK -- compare each value with the expected one
-- =====================================================================
select 'tables and views in public (expect 53)' as item, count(*)::text as value
  from information_schema.tables where table_schema = 'public'
union all select 'app functions (expect 133)', count(*)::text
  from pg_proc p join pg_namespace s on s.oid = p.pronamespace
 where s.nspname = 'public' and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
union all select 'row security policies (expect 132)', count(*)::text from pg_policies where schemaname in ('public', 'storage')
union all select 'storage buckets (expect 7)', count(*)::text from storage.buckets
union all select 'private buckets (expect 3)', count(*)::text from storage.buckets where not public
union all select 'scheduled jobs (expect 2)', count(*)::text from cron.job
union all select 'realtime tables (expect 3)', count(*)::text from pg_publication_tables
 where pubname = 'supabase_realtime' and tablename in ('notifications', 'orders', 'workers')
union all select 'barangays (expect 33)', count(*)::text from barangays
union all select 'test login accounts (>= 20)', count(*)::text from auth.users where email like '%@gentriwasa.test'
union all select 'officer accounts (expect 6)', count(*)::text from memberships where role = 'wasa_admin'
union all select 'super admins (expect 2)', count(*)::text from memberships where role = 'wasa_superadmin'
union all select 'flagged drivers (expect 1)', count(*)::text from workers where clearance_status = 'flagged'
union all select 'stations (expect 3)', count(*)::text from water_stations
union all select 'publicly listed stations (>= 2)', count(*)::text from public_stations
union all select 'station products (expect 14)', count(*)::text from station_products
union all select 'orders (> 0)', count(*)::text from orders
union all select 'bulletins (> 0)', count(*)::text from bulletins
order by item;
"""


def main():
    listing = '\n'.join(f'--     {i}. {f}' for i, (_, f, _) in enumerate(PARTS, 1))
    out = [HEADER.format(parts=listing)]
    for i, (title, name, about) in enumerate(PARTS, 1):
        body = open(os.path.join(HERE, name), encoding='utf-8').read().replace('\r\n', '\n')
        out.append(
            '\n\n\n-- =====================================================================\n'
            f'-- STEP {i} of {len(PARTS)} -- {title}  ({name})\n'
            '-- =====================================================================\n'
            f'-- {about}\n'
            '-- =====================================================================\n\n'
            + body.rstrip() + '\n'
        )
    out.append(FOOTER)
    path = os.path.join(HERE, 'setup_new_environment.sql')
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(''.join(out))
    print('wrote', path, sum(s.count('\n') for s in out), 'lines')


if __name__ == '__main__':
    main()
